CREATE TABLE account_deletion_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    user_id BIGINT NOT NULL,
    active_user_id BIGINT,
    status VARCHAR(40) NOT NULL,
    requested_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    confirmation_expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    confirmed_at TIMESTAMP(6) WITH TIME ZONE,
    cancelled_at TIMESTAMP(6) WITH TIME ZONE,
    failed_confirmation_attempts INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_account_deletion_request_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE UNIQUE INDEX uk_account_deletion_active_user ON account_deletion_requests (active_user_id);
CREATE INDEX idx_account_deletion_user_created ON account_deletion_requests (user_id, created_at);
